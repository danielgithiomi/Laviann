#!/bin/sh
# Laviann: validates a Conventional Commit header, feature scope, and branch footer.
# Invoked by .husky/commit-msg with the Git commit message file as argument.
set -eu

if [ "$#" -ne 1 ] || [ ! -f "$1" ]; then
  echo 'Usage: validate-commit-msg.sh <commit-message-file>' >&2
  exit 2
fi

file=$1
subject=$(sed '/^#/d' "$file" | sed -n '1p')
if [ -z "$subject" ]; then
  echo 'Commit rejected: message is empty.' >&2
  exit 1
fi

# Allow Git-generated merge and revert messages (preserve Git UX).
case "$subject" in
  'Merge '*|'Revert "'*'"') exit 0 ;;
esac

# The scope is mandatory because it describes the feature/code area.
# Example: feat(packaging): support custom 500g portions
allowed_types='init|feat|fix|docs|refactor|test|chore|build|ci|perf|style|revert'
pattern="^(${allowed_types})\\([a-z0-9][a-z0-9/_-]*\\)!?: [^[:space:]].*$"
if ! printf '%s\n' "$subject" | grep -Eq "$pattern"; then
  cat >&2 <<'HELP'
Commit rejected: invalid subject.
Required: <type>(<feature-scope>): <lowercase imperative description>
Types: init, feat, fix, docs, refactor, test, chore, build, ci, perf, style, revert
Example: feat(packaging): support custom 500g portions
HELP
  exit 1
fi

length=${#subject}
if [ "$length" -gt 72 ]; then
  echo "Commit rejected: subject length ${length}; maximum 72 characters." >&2
  exit 1
fi
case "$subject" in
  *.) echo 'Commit rejected: do not end subject with a period.' >&2; exit 1 ;;
esac

summary=$(printf '%s\n' "$subject" | sed -E 's/^[^:]+: //')
first_char=$(printf '%s' "$summary" | cut -c1)
if printf '%s' "$first_char" | grep -Eq '[A-Z]'; then
  echo 'Commit rejected: begin the summary with a lowercase verb.' >&2
  exit 1
fi

expected_branch=$(git symbolic-ref --quiet --short HEAD 2>/dev/null || true)
if [ -z "$expected_branch" ]; then
  echo 'Commit rejected: cannot identify a current branch. Use a named Git branch.' >&2
  exit 1
fi

# The trailer is generated by the prepare-commit-msg hook, or can be supplied
# manually. It must appear once, on a new paragraph, at the end of the message.
count=$(grep -c '^Branch:' "$file" || true)
if [ "$count" -ne 1 ]; then
  echo 'Commit rejected: expected exactly one Branch: footer.' >&2
  exit 1
fi
reported_branch=$(sed -n 's/^Branch: //p' "$file")
if [ "$reported_branch" != "$expected_branch" ]; then
  printf 'Commit rejected: Branch footer "%s" does not match current branch "%s".\n' \
    "$reported_branch" "$expected_branch" >&2
  exit 1
fi

last_content=$(sed '/^#/d; /^[[:space:]]*$/d' "$file" | tail -n 1)
if [ "$last_content" != "Branch: $expected_branch" ]; then
  echo 'Commit rejected: Branch footer must be the last non-empty line.' >&2
  exit 1
fi

if ! awk '
  /^Branch: / { if (NR < 3 || previous !~ /^[[:space:]]*$/) exit 1; found=1 }
  { previous=$0 }
  END { if (!found) exit 1 }
' "$file"; then
  echo 'Commit rejected: add a blank line before the Branch footer.' >&2
  exit 1
fi
exit 0
